function ts(daysAgo: number, hour = 10, minute = 0): Timestamp {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, minute, 0, 0);
  return Timestamp.fromDate(d);
}

function note(id: string, leadId: string, body: string, daysAgo: number, hour = 11): LeadNote {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hour, 0, 0, 0);
  return { id, leadId, body, authorUid: "uid_meedo", authorName: "محمد", createdAt: Timestamp.fromDate(d) };
}

